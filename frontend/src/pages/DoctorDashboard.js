import { useEffect, useState } from "react";
import {
  getDoctorAppointments,
  addConsultationNote,
  updateAppointment,
} from "../services/doctorService";
import './Doctor.css';

function DoctorDashboard() {
  const [appointments, setAppointments] = useState([]);
  const [selectedAppointment, setSelectedAppointment] = useState(null);
  const [notes, setNotes] = useState("");
  const [recommendations, setRecommendations] = useState("");
  const [paymentAmounts, setPaymentAmounts] = useState({});

  useEffect(() => {
    fetchAppointments();
  }, []);

  const fetchAppointments = async () => {
    try {
      const res = await getDoctorAppointments();

      const filtered = (res.data || []).filter(
        (a) => String(a.status || "").toLowerCase() === "pending consultation"
      );

      setAppointments(filtered);
    } catch (err) {
      console.error(err);
      alert("Failed to load appointments");
    }
  };

  const handlePaymentAmountChange = (appointmentId, value) => {
    setPaymentAmounts((prev) => ({
      ...prev,
      [appointmentId]: value,
    }));
  };

  const handleSubmitNotes = async () => {
    try {
      if (!selectedAppointment) return;

      await addConsultationNote({
        appointmentId: selectedAppointment.id,
        notes,
        recommendations,
      });

      alert("Notes saved successfully!");

      setSelectedAppointment(null);
      setNotes("");
      setRecommendations("");
    } catch (err) {
      console.error(err);
      alert(
        err.response?.data?.message ||
          err.response?.data ||
          "Failed to save notes"
      );
    }
  };

  const handleComplete = async (appointment) => {
    const paymentAmount = Number(paymentAmounts[appointment.id]);

    if (!paymentAmount || paymentAmount <= 0) {
      alert("Please enter a valid payment amount.");
      return;
    }

    try {
      await updateAppointment(appointment.id, {
        status: "Completed",
        paymentAmount,
      });

      alert("Consultation completed successfully!");

      setPaymentAmounts((prev) => ({
        ...prev,
        [appointment.id]: "",
      }));

      fetchAppointments();
    } catch (err) {
      console.error(err);
      alert(
        err.response?.data?.message ||
          err.response?.data ||
          "Failed to complete consultation"
      );
    }
  };

  return (
    <div style={{ padding: "20px" }}>
      <h2>Doctor Dashboard</h2>
      <h3>Pending Consultations</h3>

      {appointments.length === 0 ? (
        <p>No pending consultations.</p>
      ) : (
        appointments.map((a) => (
          <div
            key={a.id}
            style={{
              border: "1px solid #ccc",
              borderRadius: "10px",
              padding: "15px",
              marginBottom: "15px",
            }}
          >
            <h3>{a.patientName}</h3>

            <p>
              <strong>Date:</strong>{" "}
              {a.appointmentDate
                ? new Date(a.appointmentDate).toLocaleDateString()
                : "-"}
            </p>

            <p>
              <strong>Time Slot:</strong> {a.appointmentTime || "-"}
            </p>

            <p>
              <strong>Mode:</strong> {a.mode || "-"}
            </p>

            <p>
              <strong>Notes:</strong> {a.notes || "None"}
            </p>

            <p>
              <strong>System Auto Details:</strong>{" "}
              {a.mode === "Online"
                ? "Meeting link will be auto-generated by the system"
                : "Physical location will be auto-filled from doctor profile"}
            </p>

            <div style={{ marginTop: "10px" }}>
              <button onClick={() => setSelectedAppointment(a)}>
                Add Notes
              </button>
            </div>

            <div style={{ marginTop: "10px" }}>
              <input
                type="number"
                placeholder="Enter payment amount"
                value={paymentAmounts[a.id] || ""}
                onChange={(e) =>
                  handlePaymentAmountChange(a.id, e.target.value)
                }
              />
            </div>

            <button
              onClick={() => handleComplete(a)}
              style={{ marginTop: "10px" }}
            >
              Mark Completed
            </button>
          </div>
        ))
      )}

      {selectedAppointment && (
        <div style={{ marginTop: "20px" }}>
          <h3>Add Consultation Notes</h3>

          <div style={{ marginBottom: "10px" }}>
            <textarea
              placeholder="Notes"
              value={notes}
              onChange={(e) => setNotes(e.target.value)}
              rows="4"
              cols="60"
            />
          </div>

          <div style={{ marginBottom: "10px" }}>
            <textarea
              placeholder="Recommendations"
              value={recommendations}
              onChange={(e) => setRecommendations(e.target.value)}
              rows="4"
              cols="60"
            />
          </div>

          <button onClick={handleSubmitNotes} style={{ marginRight: "10px" }}>
            Submit
          </button>

          <button
            onClick={() => {
              setSelectedAppointment(null);
              setNotes("");
              setRecommendations("");
            }}
          >
            Cancel
          </button>
        </div>
      )}
    </div>
  );
}

export default DoctorDashboard;